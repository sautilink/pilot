import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import vm from 'node:vm';

const directory = new URL('../src/vendor/public-icons/', import.meta.url);
const escape = value => String(value).replace(/[&<>\"]/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[character]));
const sha256 = value => createHash('sha256').update(value).digest('hex');
const tags = new Set(['svg', 'g', 'path', 'circle', 'line', 'rect']);
const attributes = new Set(['xmlns', 'viewBox', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'd', 'stroke-dasharray', 'stroke-dashoffset', 'cx', 'cy', 'r', 'x1', 'x2', 'y1', 'y2', 'x', 'y', 'width', 'height', 'rx', 'ry', 'pathLength']);

// This minimal DOM exists only in the Node build/test process. Render through
// Router's actual runtime so the static fallback includes its normal styles,
// grouping and geometry rather than a separately maintained drawing.
class StaticElement {
  constructor(tag) {
    if (!tags.has(tag)) throw new Error(`Unreviewed SVG element: ${tag}`);
    this.tag = tag;
    this.attributes = new Map();
    this.children = [];
    this.styles = new Map();
    this.style = {
      setProperty: (name, value) => {
        if (!/^[a-z-]+$/.test(name) || /[<>]|url\s*\(|expression\s*\(/i.test(value)) throw new Error('Unsafe SVG style');
        this.styles.set(name, String(value));
      },
    };
  }
  setAttribute(name, value) {
    if (!attributes.has(name)) throw new Error(`Unreviewed SVG attribute: ${name}`);
    this.attributes.set(name, String(value));
  }
  appendChild(child) { this.children.push(child); return child; }
  get outerHTML() {
    const values = [...this.attributes];
    if (this.styles.size) values.push(['style', [...this.styles].map(([name, value]) => `${name}: ${value}`).join('; ')]);
    return `<${this.tag}${values.map(([name, value]) => ` ${name}="${escape(value)}"`).join('')}>${this.children.map(child => child.outerHTML).join('')}</${this.tag}>`;
  }
}

export function renderStaticIcons(source) {
  const sandbox = Object.create(null);
  vm.runInNewContext(source, sandbox, { filename: 'Router/public-icons/icons.js', timeout: 2000 });
  const runtime = sandbox.SautiPublicIcons;
  if (!runtime?.renderIcon || !runtime.catalog || !runtime.names?.length) throw new Error('Unexpected Router icon runtime');
  const document = {
    createElementNS(namespace, tag) {
      if (namespace !== 'http://www.w3.org/2000/svg') throw new Error('Unexpected icon namespace');
      return new StaticElement(tag);
    },
  };
  return Object.fromEntries([...runtime.names].sort().map(name => [name, runtime.renderIcon(name, 24, document).outerHTML]));
}

export async function buildPublicIcons() {
  const types = {
    'icons.js': 'application/javascript; charset=utf-8',
    'adapter.js': 'application/javascript; charset=utf-8',
    'icons.css': 'text/css; charset=utf-8',
    'manifest.json': 'application/json; charset=utf-8',
    'LICENSE': 'text/plain; charset=utf-8',
    'LICENSE-MOTION.md': 'text/plain; charset=utf-8',
    'NOTICE.md': 'text/plain; charset=utf-8',
    'THIRD_PARTY_NOTICES.md': 'text/plain; charset=utf-8',
  };
  const assets = {};
  for (const [name, type] of Object.entries(types)) {
    const text = await readFile(new URL(name, directory), 'utf8');
    assets[name] = { text, type, sha256: sha256(text), bytes: Buffer.byteLength(text) };
  }
  const icons = renderStaticIcons(assets['icons.js'].text);
  const manifest = JSON.parse(assets['manifest.json'].text);
  if (manifest.package !== '@animateicons/vanilla' || manifest.version !== '0.1.0' ||
    JSON.stringify([...manifest.names].sort()) !== JSON.stringify(Object.keys(icons))) throw new Error('Router manifest/catalog mismatch');
  const version = sha256(JSON.stringify(assets)).slice(0, 20);
  const header = '// Generated by node scripts/build-public-icons.mjs. Do not edit.\n// Browser code is data here; importing this module never executes it.\n';
  await writeFile(new URL('assets.generated.js', directory), `${header}export const PUBLIC_ICON_VERSION = ${JSON.stringify(version)};\nexport const PUBLIC_ICON_ASSETS = ${JSON.stringify(assets)};\n`);
  await writeFile(new URL('static.generated.js', directory), `${header}export const STATIC_ICONS = Object.freeze(${JSON.stringify(icons)});\n`);
  return { icons: Object.keys(icons).length, version, runtimeSha256: assets['icons.js'].sha256 };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  console.info(await buildPublicIcons());
}
